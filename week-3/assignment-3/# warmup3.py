print(not True and False) # False because both conditions state False
print(True or False and False) # True because only one of the conditions has to be true for an "or" statement
print(not (5 > 3)) # False because 5>3 is true but there is the inverse of "not"
print(10 == 10 and 4 != 4) # False because the "and" statement requires both conditions to be true but only the first one is
print(not False or not True) # True because this is the same as "True or False"